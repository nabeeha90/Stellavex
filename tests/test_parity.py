"""Checks that the Python simulation matches the game's JavaScript engine exactly.

golden.json was generated by running the game's own engine (including random in-flight decisions)
on 1,200 random designs.   Run:  python -m unittest discover -s tests
"""
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
import sim  # noqa: E402

DESIGN = {"r": "condor", "b": "hydrolox", "f": 6000, "p": ["rover", "atmo", "relay"], "t": "slow", "w": "solar_l", "y": "bat_s", "a": "mga", "o": "high", "l": "opt"}


class Parity(unittest.TestCase):
    def test_matches_game_engine(self):
        cases = json.loads((Path(__file__).parent / "golden.json").read_text())
        bad = []
        for c in cases:
            r = sim.simulate(c["design"], c["seed"], c["mission"], c["difficulty"], c["upgrades"], c["choices"])
            e = c["expect"]
            got = {"score": r["score"], "landed": r["landed"], "stages": [x["ok"] for x in r["stages"]], "dets": [x["det"] for x in r["stages"]],
                   "power": r["_ratios"]["power"], "comms": r["_ratios"]["comms"]}
            if got != e:
                bad.append((c["mission"], c["difficulty"], c["seed"], got["score"], e["score"]))
        self.assertEqual(bad[:5], [], "%d of %d cases differ" % (len(bad), len(cases)))

    def test_same_seed_same_result(self):
        self.assertEqual(sim.simulate(DESIGN, 7, "mars"), sim.simulate(DESIGN, 7, "mars"))

    def test_decisions_change_outcomes(self):
        outcomes = {tuple(sim.simulate(DESIGN, seed, "mars", "standard", (), [c] * 6)["score"] for seed in range(1, 60)) for c in ("accept", "divert", "ride", "safe", "wait", "land", "go")}
        self.assertGreater(len(outcomes), 1)

    def test_rejects_bad_designs(self):
        with self.assertRaises(sim.DesignError):
            sim.simulate(dict(DESIGN, r="sparrow", f=6500), 1, "mars")
        with self.assertRaises(sim.DesignError):
            sim.simulate(dict(DESIGN, r="nope"), 1, "mars")
        with self.assertRaises(sim.DesignError):
            sim.simulate(dict(DESIGN, a="no-such-antenna"), 1, "mars")


if __name__ == "__main__":
    unittest.main()
